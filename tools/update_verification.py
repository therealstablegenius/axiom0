#!/usr/bin/env python3
"""Keep docs/VERIFICATION.md honest: the test counts in it are generated, not typed.

  python3 tools/update_verification.py          # run the suite, rewrite the generated block
  python3 tools/update_verification.py --check  # CI: fail if the doc is out of date or tests fail

Only the text between the GENERATED markers is replaced. The block records the
version, how many tests exist per file, and how many passed, so the document
cannot drift from the code again (v0.6 docs still said 12/18 tests while 27 existed).
"""
from __future__ import annotations
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / 'docs' / 'VERIFICATION.md'
BEGIN, END = '<!-- GENERATED:tests BEGIN -->', '<!-- GENERATED:tests END -->'


def collect() -> Counter:
    out = subprocess.run([sys.executable, '-m', 'pytest', '--collect-only', '-q', 'tests'],
                         cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return Counter(line.split('::', 1)[0] for line in out.splitlines() if '::' in line)


def run_suite() -> tuple[int, int, int]:
    proc = subprocess.run([sys.executable, '-m', 'pytest', '-q', 'tests'], cwd=ROOT, capture_output=True, text=True)
    tail = proc.stdout.strip().splitlines()[-1] if proc.stdout.strip() else ''
    nums = {k: int(v) for v, k in re.findall(r'(\d+) (passed|failed|error|errors|skipped)', tail)}
    return nums.get('passed', 0), nums.get('failed', 0) + nums.get('error', 0) + nums.get('errors', 0), nums.get('skipped', 0)


def render(per_file: Counter, passed: int, failed: int, skipped: int) -> str:
    sys.path.insert(0, str(ROOT))
    from axiom0 import __version__
    total = sum(per_file.values())
    rows = '\n'.join(f'| `{name}` | {n} |' for name, n in sorted(per_file.items()))
    status = 'all passing' if failed == 0 and passed + skipped == total else f'{failed} FAILING'
    return (f'{BEGIN}\n'
            f'**AXIOM0 {__version__}: {total} automated tests, {passed} passed'
            f'{f", {skipped} skipped" if skipped else ""} ({status}).**\n\n'
            f'| Test file | Tests |\n|---|---|\n{rows}\n\n'
            f'_Generated by `tools/update_verification.py`; CI fails if this block is stale._\n'
            f'{END}')


def main(argv: list[str]) -> int:
    per_file = collect()
    passed, failed, skipped = run_suite()
    block = render(per_file, passed, failed, skipped)
    text = DOC.read_text(encoding='utf-8')
    if BEGIN not in text or END not in text:
        print('docs/VERIFICATION.md has no GENERATED markers', file=sys.stderr)
        return 2
    new = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda _: block, text, flags=re.S)
    if '--check' in argv:
        if failed:
            print(f'{failed} test(s) failing', file=sys.stderr)
            return 1
        if new != text:
            print('docs/VERIFICATION.md is out of date: run python3 tools/update_verification.py', file=sys.stderr)
            return 1
        print('VERIFICATION.md matches the test suite.')
        return 0
    DOC.write_text(new, encoding='utf-8')
    print(block)
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
